"""Build the folder that gets uploaded to a Hugging Face Space.

A Space is a small git repository on the Hub. This script copies *only* what the Space needs
into one folder, so nothing private (``.env``, the dataset, planning notes) can slip in:

    app.py                      the composition root
    contracts/src/...           the three package source trees (no tests)
    backend/src/...
    frontend/src/...
    README.md                   generated; its YAML header is the Space configuration
    requirements.txt            generated from ``uv.lock`` (pinned, no hashes)

Two ways of making the three packages importable on the Space exist:

* ``syspath`` (default): only third-party libraries are installed, and ``app.py`` adds the
  three ``src`` folders to ``sys.path`` itself.
* ``editable``: ``requirements.txt`` also lists ``./contracts``, ``./backend`` and
  ``./frontend``. Hugging Face may install requirements from a copy outside the repository,
  where those relative paths cannot resolve, so this is only kept to compare against.

Usage::

    uv run python -m scripts.space_bundle [--out build/space] [--packaging syspath] [--json]
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
import tomllib
from enum import StrEnum
from pathlib import Path

import yaml
from pydantic import BaseModel, ConfigDict

REPO_ROOT = Path(__file__).resolve().parents[1]
PACKAGES = ("contracts", "backend", "frontend")
# Anything here must never reach the Hub.
_FORBIDDEN_TOP_LEVEL = {"data", ".planning", ".claude", ".git", ".tools", "build"}
_FORBIDDEN_SUFFIXES = {".parquet", ".safetensors", ".bin", ".pt", ".pth", ".ckpt", ".onnx", ".gguf"}


class Packaging(StrEnum):
    """How the three workspace packages become importable on the Space."""

    SYSPATH = "syspath"
    EDITABLE = "editable"


class BundleError(Exception):
    """Raised when the bundle would contain something that must not be uploaded."""


class BundleReport(BaseModel):
    """What :func:`build_bundle` produced."""

    model_config = ConfigDict(frozen=True)

    out_dir: Path
    files: tuple[str, ...]
    sdk_version: str
    packaging: Packaging


def locked_version(repo_root: Path, package_name: str) -> str:
    """Return the version of ``package_name`` pinned in ``uv.lock``."""
    lock = tomllib.loads((repo_root / "uv.lock").read_text(encoding="utf-8"))
    for package in lock["package"]:
        if package["name"] == package_name:
            version: str = package["version"]
            return version
    msg = f"{package_name} is not in uv.lock"
    raise BundleError(msg)


def render_space_readme(*, sdk_version: str) -> str:
    """Return the Space README: a YAML header (the Space settings) plus a short body."""
    header = {
        "title": "KhetSetu",
        "emoji": "\N{EAR OF RICE}",
        "colorFrom": "green",
        "colorTo": "yellow",
        "sdk": "gradio",
        "sdk_version": sdk_version,
        # A string on purpose: a bare 3.12 would be read by YAML as the number 3.12.
        "python_version": "3.12",
        "app_file": "app.py",
        "pinned": False,
        "short_description": "Plant-disease assistant for farmers (demo skeleton)",
    }
    front_matter = yaml.safe_dump(header, sort_keys=False, allow_unicode=True)
    body = (
        "# KhetSetu\n\n"
        "This file is generated by `scripts/space_bundle.py`. Do not edit it here; "
        "change the script instead.\n"
    )
    return f"---\n{front_matter}---\n\n{body}"


def export_requirements(repo_root: Path) -> str:
    """Return the pinned runtime dependencies of the application (no dev tools, no hashes)."""
    uv = shutil.which("uv")
    if uv is None:
        msg = "the 'uv' command was not found on PATH"
        raise BundleError(msg)
    result = subprocess.run(  # noqa: S603 - fixed argument list, no shell
        [
            uv,
            "export",
            "--locked",
            "--no-dev",
            "--no-hashes",
            "--no-emit-workspace",
            "--package",
            "khetsetu",
        ],
        cwd=repo_root,
        check=True,
        capture_output=True,
        text=True,
    )
    return result.stdout


def _skip_noise(_directory: str, names: list[str]) -> set[str]:
    """``shutil.copytree`` ignore callback: no tests, caches or bytecode."""
    return {name for name in names if name in {"__pycache__", "tests"} or name.endswith(".pyc")}


def stage_bundle(repo_root: Path, out_dir: Path, packaging: Packaging) -> None:
    """Copy the allow-listed files (and nothing else) into ``out_dir``."""
    out_dir.mkdir(parents=True)
    shutil.copy2(repo_root / "app.py", out_dir / "app.py")
    for package in PACKAGES:
        shutil.copytree(repo_root / package / "src", out_dir / package / "src", ignore=_skip_noise)
        if packaging is Packaging.EDITABLE:
            shutil.copy2(
                repo_root / package / "pyproject.toml", out_dir / package / "pyproject.toml"
            )


def assert_bundle_clean(out_dir: Path) -> None:
    """Raise :class:`BundleError` if a secret, dataset, weight file or tool folder is present.

    A *nested* folder called ``data`` is fine (``khetsetu_backend.data`` is source code);
    only a top-level ``data`` folder is the dataset.
    """
    problems = [e.name for e in out_dir.iterdir() if e.name in _FORBIDDEN_TOP_LEVEL]
    problems += [
        str(path.relative_to(out_dir))
        for path in out_dir.rglob("*")
        if path.is_file()
        and (path.name.startswith(".env") or path.suffix.lower() in _FORBIDDEN_SUFFIXES)
    ]
    if problems:
        msg = f"refusing to bundle forbidden files: {sorted(set(problems))}"
        raise BundleError(msg)


def build_bundle(repo_root: Path, out_dir: Path, packaging: Packaging) -> BundleReport:
    """Create ``out_dir`` from scratch and return a report. Same inputs, same bytes."""
    sdk_version = locked_version(repo_root, "gradio")
    if out_dir.exists():
        shutil.rmtree(out_dir)
    stage_bundle(repo_root, out_dir, packaging)
    requirements = export_requirements(repo_root)
    if packaging is Packaging.EDITABLE:
        requirements += "".join(f"./{package}\n" for package in PACKAGES)
    (out_dir / "requirements.txt").write_text(requirements, encoding="utf-8")
    (out_dir / "README.md").write_text(
        render_space_readme(sdk_version=sdk_version), encoding="utf-8"
    )
    assert_bundle_clean(out_dir)
    files = tuple(sorted(str(p.relative_to(out_dir)) for p in out_dir.rglob("*") if p.is_file()))
    return BundleReport(out_dir=out_dir, files=files, sdk_version=sdk_version, packaging=packaging)


def main(argv: list[str] | None = None) -> int:
    """Command line entry point; returns the exit code."""
    parser = argparse.ArgumentParser(description="Build the Hugging Face Space upload folder.")
    parser.add_argument("--out", type=Path, default=REPO_ROOT / "build" / "space")
    parser.add_argument("--packaging", type=Packaging, choices=list(Packaging), default="syspath")
    parser.add_argument("--json", action="store_true", help="print the report as JSON")
    args = parser.parse_args(argv)
    try:
        report = build_bundle(REPO_ROOT, args.out, Packaging(args.packaging))
    except (BundleError, subprocess.CalledProcessError) as error:
        sys.stderr.write(f"bundle failed: {error}\n")
        return 1
    if args.json:
        sys.stdout.write(report.model_dump_json(indent=2) + "\n")
    else:
        sys.stdout.write(f"Bundle written to {report.out_dir} ({len(report.files)} files)\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
